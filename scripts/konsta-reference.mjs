// Writes konsta/REFERENCE.md from the installed Konsta React types: one line per component with its
// props, types and one-line meaning. The model has no other way to know Konsta's API (there is no MCP
// and v5 is newer than most training data), and the Framework7 trial showed an official API sheet cuts
// wrong props sharply. Run again after `npm i konsta@x` in prototypes/vita-konsta; a test holds the
// file to the installed version.
//   node scripts/konsta-reference.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const TYPES = join(ROOT, 'prototypes/vita-konsta/node_modules/konsta/react/types')
const version = JSON.parse(readFileSync(join(ROOT, 'prototypes/vita-konsta/node_modules/konsta/package.json'), 'utf8')).version

// Props that are theme plumbing, not design: the model writes `className`, never these.
const SKIP = /^(component|ref|colors|.*ClassName|fontSize(Ios|Material)?|.*FontSize(Ios|Material)?|touchRipple|translucent|scrollEl|inputId|inputStyle)$/
const THEME = /(Ios|Material)$/

export function parseProps(dts) {
  const lines = dts.split('\n')
  const props = []
  let depth = 0, inColors = false, doc = []
  for (const raw of lines) {
    const line = raw.trim()
    if (inColors) { if (/^};?$/.test(line)) inColors = false; continue }
    if (/^colors\?:\s*\{/.test(line)) { inColors = true; continue }
    if (line.startsWith('/**')) { doc = []; continue }
    if (line.startsWith('*') && !line.startsWith('*/')) { const t = line.replace(/^\*\s?/, '').trim(); if (t && !t.startsWith('@default')) doc.push(t.replace(/\s*\*\/\s*$/, '')); continue }
    const m = line.match(/^([a-zA-Z][\w]*)(\?)?:\s*(.+?);?$/)
    if (m && depth === 0) {
      const text = doc.join(' ').replace(/`/g, '')
      // The prop's name already says "content of the X area" and "allows to open/close".
      props.push({ name: m[1], type: m[3].replace(/\s+/g, ' ').trim(), doc: /^(Content of|Allows to open\/close|Click handler on backdrop)/.test(text) ? '' : text })
      doc = []
    }
  }
  return props
}

function shorten(type) {
  return type
    .replace(/string \| number \| React\.ReactNode/g, 'node')
    .replace(/React\.ReactNode/g, 'node')
    .replace(/React\.(ComponentType<any>|Ref<[^>]+>)/g, 'any')
    .replace(/\(e: any\) => void/g, 'fn')
    .replace(/\(.*?\) => void/g, 'fn')
    .replace(/\bboolean\b/g, 'bool')
}

const out = [`# Konsta UI ${version} — React components (generated by scripts/konsta-reference.mjs; do not edit)`,
  '', 'Every component also takes `className` and the usual DOM props. `Ios`/`Material` suffixed props were folded into their base name. Types: bool, string, number, node (text or JSX), fn.', '']
const files = readdirSync(TYPES).filter((f) => f.endsWith('.d.ts')).sort()
const names = []
for (const f of files) {
  const name = f.replace('.d.ts', '')
  names.push(name)
  const seen = new Map()
  for (const p of parseProps(readFileSync(join(TYPES, f), 'utf8'))) {
    if (SKIP.test(p.name)) continue
    const base = THEME.test(p.name) ? p.name.replace(THEME, '') : p.name
    if (seen.has(base) && base !== p.name) continue
    seen.set(base, { ...p, name: base })
  }
  const props = [...seen.values()]
  const cells = props.map((p) => {
    const t = shorten(p.type)
    const d = p.doc && !/^(Enables|Renders|Makes|Adds) /.test(p.doc) && p.doc.length <= 60 ? ` — ${p.doc}` : p.doc && p.doc.length <= 60 ? ` — ${p.doc.replace(/^(Enables|Renders|Makes|Adds) /, '').replace(/^\w/, (c) => c.toLowerCase())}` : ''
    return `\`${p.name}\`${t === 'bool' ? '' : `: ${t}`}${d}`
  })
  out.push(`- **${name}** — ${cells.length ? cells.join('; ') : 'children only'}`)
}
out.push('', `Exports: ${names.join(', ')}`)
writeFileSync(join(ROOT, 'konsta/REFERENCE.md'), out.join('\n') + '\n')
console.log(`${files.length} components, ${out.join('\n').length} chars`)
